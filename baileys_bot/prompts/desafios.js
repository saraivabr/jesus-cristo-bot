/**
 * Retorna um desafio baseado no tema e nível do usuário
 */
export function getDesafio(tema, perfil = {}) {
  const nivel = perfil.nivel || 'iniciante';
  const desafiosRealizados = perfil.desafios_realizados || [];

  let listaDesafios = [];

  // Primeiro tenta pegar do tema específico
  if (desafios[tema]) {
    listaDesafios = desafios[tema];
  } else {
    // Se não encontrar o tema, usa geral
    listaDesafios = desafios.geral;
  }

  // Filtra desafios já realizados
  const disponiveis = listaDesafios.filter(d =>
    !desafiosRealizados.includes(d.texto)
  );

  // Se todos já foram feitos, reseta
  const lista = disponiveis.length > 0 ? disponiveis : listaDesafios;

  // Filtra por dificuldade baseado no nível
  let dificuldadeAlvo;
  switch (nivel) {
    case 'curioso':
    case 'buscador':
      dificuldadeAlvo = 'facil';
      break;
    case 'iniciante':
    case 'crescendo':
      dificuldadeAlvo = 'medio';
      break;
    case 'maduro':
      dificuldadeAlvo = 'dificil';
      break;
    default:
      dificuldadeAlvo = 'facil';
  }

  // Tenta achar da dificuldade certa, senão pega qualquer um
  const daDificuldade = lista.filter(d => d.dificuldade === dificuldadeAlvo);
  const final = daDificuldade.length > 0 ? daDificuldade : lista;

  return final[Math.floor(Math.random() * final.length)];
}

/**
 * Retorna um desafio específico para o nível espiritual
 */
export function getDesafioPorNivel(nivel) {
  const lista = desafiosPorNivel[nivel] || desafiosPorNivel.iniciante;
  return lista[Math.floor(Math.random() * lista.length)];
}

/**
 * Formata o desafio no estilo de Jesus
 */
export function formatarDesafio(desafio) {
  const texto = typeof desafio === 'string' ? desafio : desafio.texto;

  const intros = [
    "Agora um desafio pra você:",
    "Quero te propor algo:",
    "Faz isso por mim:",
    "Um exercício pra hoje:",
    "Tenta fazer isso:",
    "Minha proposta pra você:"
  ];

  const fechamentos = [
    "\n\nMe conta depois como foi?",
    "\n\nDepois você me conta o que sentiu.",
    "\n\nVolta aqui e me diz como foi.",
    "\n\nQuero saber como foi pra você.",
    "\n\nE aí, topa?"
  ];

  const intro = intros[Math.floor(Math.random() * intros.length)];
  const fechamento = fechamentos[Math.floor(Math.random() * fechamentos.length)];

  return `${intro}\n\n*${texto}*${fechamento}`;
}

/**
 * Retorna todos os temas disponíveis
 */
export function getTemas() {
  return Object.keys(desafios);
}

/**
 * Retorna desafios urgentes (para agora)
 */
export function getDesafioUrgente(tema) {
  const lista = desafios[tema] || desafios.geral;
  const urgentes = lista.filter(d => d.duracao === 'agora');

  if (urgentes.length > 0) {
    return urgentes[Math.floor(Math.random() * urgentes.length)];
  }

  // Se não tem urgente, retorna qualquer um fácil
  const faceis = lista.filter(d => d.dificuldade === 'facil');
  return faceis[Math.floor(Math.random() * faceis.length)] || lista[0];
}

