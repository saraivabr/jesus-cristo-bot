export function getVersiculoPorTema(tema) {
  const temaLower = tema.toLowerCase();
  if (versiculos[temaLower]) {
    const lista = versiculos[temaLower];
    return lista[Math.floor(Math.random() * lista.length)];
  }
  return null;
}

export function getVersiculoPorHumor(mood) {
  const moodToTema = {
    'triste': 'tristeza',
    'ansioso': 'ansiedade',
    'com_medo': 'medo',
    'culpado': 'culpa',
    'sozinho': 'solidao',
    'perdido': 'proposito',
    'grato': 'gratidao',
    'esperancoso': 'esperanca',
    'neutro': 'fe'
  };

  const tema = moodToTema[mood] || 'fe';
  return getVersiculoPorTema(tema);
}

export function getPassagem(nome) {
  return passagens[nome] || null;
}

export function getPassagemPorTema(tema) {
  const temaLower = tema.toLowerCase();
  const passagensComTema = Object.values(passagens).filter(p =>
    p.temas && p.temas.includes(temaLower)
  );

  if (passagensComTema.length > 0) {
    return passagensComTema[Math.floor(Math.random() * passagensComTema.length)];
  }
  return null;
}

export function getBeatitudeAleatoria() {
  return beatitudes[Math.floor(Math.random() * beatitudes.length)];
}

export function searchByKeyword(keyword) {
  const keywordLower = keyword.toLowerCase();
  const results = [];

  // Busca em versículos
  for (const [tema, lista] of Object.entries(versiculos)) {
    for (const v of lista) {
      if (
        v.texto.toLowerCase().includes(keywordLower) ||
        v.aplicacao.toLowerCase().includes(keywordLower) ||
        tema.includes(keywordLower)
      ) {
        results.push({ type: 'versiculo', tema, ...v });
      }
    }
  }

  // Busca em passagens
  for (const [nome, p] of Object.entries(passagens)) {
    if (
      p.titulo.toLowerCase().includes(keywordLower) ||
      p.resumo.toLowerCase().includes(keywordLower) ||
      (p.temas && p.temas.some(t => t.includes(keywordLower)))
    ) {
      results.push({ type: 'passagem', nome, ...p });
    }
  }

  return results;
}

export function getTemas() {
  return Object.keys(versiculos);
}

export function getPassagens() {
  return Object.keys(passagens);
}

